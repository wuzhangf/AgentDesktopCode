using System.Diagnostics;
using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using AgentLink;

if (args is ["health", var directory, var buildText])
{
    if (File.ReadAllText(Path.Combine(directory, "AgentLink.exe")) != "tray-" + buildText ||
        File.ReadAllText(Path.Combine(directory, "host", "AgentLink.Host.exe")) != "host-" + buildText)
        Environment.ExitCode = 1;
    return;
}

if (args is ["verify-build-output", var builtArchive, var expectedBuild])
{
    var target = ReadTarget(long.Parse(expectedBuild), builtArchive);
    var testRoot = Path.Combine(Path.GetTempPath(), "link-build-output-" + Guid.NewGuid().ToString("N"));
    try
    {
        var store = new PayloadActivation(testRoot, release => release == target);
        Check((await store.ActivateAsync(target, builtArchive, Pause, Healthy)).Status == ActivationStatus.Committed,
            "packaging output is consumable");
        Check(store.Recover()?.Release == target, "packaging output remains verified");
        Console.WriteLine("PASS: the ZIP and manifest generated by the packaging script activate and reverify.");
    }
    finally
    {
        if (Directory.Exists(testRoot)) Directory.Delete(testRoot, recursive: true);
    }
    return;
}

if (args is ["interrupted", var root, var archivePath, var marker])
{
    var release = ReadTarget(44, archivePath);
    var previous = ReadTarget(42, Path.Combine(Path.GetDirectoryName(archivePath)!, "42.zip"));
    var active = new PayloadActivation(root, target => target == previous || target == release);
    await active.ActivateAsync(release, archivePath, Pause, async (_, cancellation) =>
    {
        File.WriteAllText(marker, "probe");
        await Task.Delay(Timeout.InfiniteTimeSpan, cancellation);
        return true;
    });
    throw new InvalidOperationException("Crash fixture ended early.");
}

var scratch = Path.Combine(Path.GetTempPath(), "link-payload-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(scratch);
try
{
    var state = Path.Combine(scratch, "slots");
    var first = CreatePayload(scratch, 41);
    var next = CreatePayload(scratch, 42);
    var bad = CreatePayload(scratch, 43);
    var interrupted = CreatePayload(scratch, 44);
    var targets = new HashSet<PayloadRelease> { first.Target, next.Target, bad.Target, interrupted.Target };
    var store = new PayloadActivation(state, targets.Contains);
    var business = Path.Combine(scratch, "user-state.db");
    File.WriteAllText(business, "unchanged");
    var unverifiedPublisher = new PayloadActivation(state, targets.Contains,
        _ => throw new CryptographicException("Unexpected test publisher."));
    await ExpectAsync<CryptographicException>(() => unverifiedPublisher.ActivateAsync(first.Target, first.Path,
        _ => throw new InvalidOperationException("An unverified publisher reached quiescing."), Healthy));
    Check(unverifiedPublisher.Recover() is null, "publisher rejection created a runnable selection");
    Check(store.Recover() is null, "an empty store has no runnable version");
    var installed = await store.ActivateAsync(first.Target, first.Path, Pause, Healthy);
    Check(installed.Status == ActivationStatus.Committed && installed.Current?.Release == first.Target, "seed commit");
    var busy = await store.ActivateAsync(next.Target, next.Path, _ => Task.FromResult<IAsyncDisposable?>(null),
        (_, _) => throw new InvalidOperationException("Busy application's probe was called."));
    Check(busy.Status == ActivationStatus.Busy && store.Recover()?.Release == first.Target, "busy leaves the seed running");
    Check(!Directory.Exists(Path.Combine(state, "versions", "42")), "a deferred update keeps no third installed slot");
    await ExpectAsync<IOException>(() => store.ActivateAsync(next.Target, next.Path, Pause, Healthy,
        confirmCommit: _ => throw new IOException("Fresh signed metadata temporarily unavailable.")));
    Check(store.Recover()?.Release == first.Target, "confirmation failure preserves current and permits the same candidate later");
    var succeeded = await store.ActivateAsync(next.Target, next.Path, Pause, (payload, cancellation) =>
    {
        Check(File.ReadAllText(Path.Combine(payload.Directory, "AgentLink.exe")) == "tray-42", "candidate path is version-specific");
        Expect<IOException>(() => store.Recover());
        var journal = File.ReadAllText(Path.Combine(state, "activation.json"));
        Check(journal.Contains("\"current\":{\"buildNumber\":41") &&
            journal.Contains("\"pending\":{\"buildNumber\":42"), "current build remains selected during health");
        return Healthy(payload, cancellation);
    });
    Check(succeeded.Status == ActivationStatus.Committed && store.Recover()?.Release == next.Target, "health commits the new build");
    var rejected = await store.ActivateAsync(bad.Target, bad.Path, Pause, (_, _) => Task.FromResult(false));
    Check(rejected.Status == ActivationStatus.Rejected && store.Recover()?.Release == next.Target, "failed health preserves current");
    var repeated = await store.ActivateAsync(bad.Target, bad.Path, Pause,
        (_, _) => throw new InvalidOperationException("Failed build was tried again."));
    Check(repeated.Status == ActivationStatus.Rejected, "failed build is suppressed");
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(first.Target, first.Path, Pause, Healthy));
    Console.WriteLine("PASS: busy deferral, fenced health, atomic version selection, failure and downgrade handling.");

    var signal = Path.Combine(scratch, "probe.started");
    using (var child = Start("interrupted", state, interrupted.Path, signal))
    {
        try
        {
            var deadline = Stopwatch.StartNew();
            while (!File.Exists(signal) && !child.HasExited && deadline.Elapsed < TimeSpan.FromSeconds(10))
                await Task.Delay(30);
            Check(File.Exists(signal) && !child.HasExited, "child reached actual probe under the activation lock");
            child.Kill();
            using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(10));
            await child.WaitForExitAsync(timeout.Token);
        }
        finally
        {
            if (!child.HasExited) child.Kill();
        }
    }
    Check(store.Recover()?.Release == next.Target, "fresh recovery resumes the last committed version");
    Check(store.Inspect().Runnable?.Release == next.Target &&
        !Directory.Exists(Path.Combine(state, "versions", "44")), "recovery prunes the interrupted candidate slot");
    Check(File.ReadAllText(business) == "unchanged", "activation never opens the business-state directory");
    Console.WriteLine("PASS: force-killed activation released its lock and recovered the previous committed build.");

    var invalidBuild = 60;
    foreach (var file in new[] { "../outside.exe", "aux.txt", "host/a.exe:stream", "Host/AGENTLINK.HOST.EXE" })
    {
        var invalid = CreatePayload(scratch, invalidBuild++, file);
        targets.Add(invalid.Target);
        await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(invalid.Target, invalid.Path, Pause, Healthy));
    }
    Check(!File.Exists(Path.Combine(scratch, "outside.exe")), "payload extraction is confined");
    var linked = CreatePayload(scratch, 51, "lib/link.dll", unchecked((int)0xa1ff0000));
    targets.Add(linked.Target);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(linked.Target, linked.Path, Pause, Healthy));
    var mismatch = CreatePayload(scratch, 52, badHash: true);
    targets.Add(mismatch.Target);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(mismatch.Target, mismatch.Path, Pause, Healthy));
    var unknown = CreatePayload(scratch, 53);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(unknown.Target, unknown.Path, Pause, Healthy));
    var replaced = CreatePayload(scratch, 54);
    targets.Add(replaced.Target);
    File.AppendAllText(replaced.Path, "changed archive");
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(replaced.Target, replaced.Path, Pause, Healthy));
    var modified = CreatePayload(scratch, 55);
    targets.Add(modified.Target);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(modified.Target, modified.Path, Pause, (payload, _) =>
    {
        File.AppendAllText(Path.Combine(payload.Directory, "AgentLink.exe"), "changed during health");
        return Task.FromResult(true);
    }));
    Check(store.Recover()?.Release == next.Target, "candidate changes before commit preserve the old build");
    File.WriteAllText(Path.Combine(succeeded.Current!.Directory, "unexpected.dll"), "side-load");
    Expect<InvalidDataException>(() => store.Recover());
    File.Delete(Path.Combine(succeeded.Current.Directory, "unexpected.dll"));
    var revokedFallback = CreatePayload(scratch, 56);
    targets.Add(revokedFallback.Target);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(revokedFallback.Target, revokedFallback.Path, Pause,
        (_, _) =>
        {
            targets.Remove(next.Target);
            return Task.FromResult(false);
        }));
    Expect<InvalidDataException>(() => store.Recover());
    Console.WriteLine("PASS: untrusted archives, redirected paths, hash changes, extra files and revoked current builds fail closed.");

    Check(store.Inspect() is { Runnable: null } selection && selection.Committed == next.Target,
        "withdrawal preserves the repair floor and cannot make the old slot runnable");
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(first.Target, first.Path,
        _ => throw new InvalidOperationException("Repair attempted a downgrade."), Healthy,
        confirmCommit: _ => Task.CompletedTask, repair: true));
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(unknown.Target, unknown.Path,
        _ => throw new InvalidOperationException("Repair attempted an unsigned target."), Healthy,
        confirmCommit: _ => Task.CompletedTask, repair: true));
    var repair = CreatePayload(scratch, 57);
    targets.Add(repair.Target);
    await ExpectAsync<InvalidDataException>(() => store.ActivateAsync(repair.Target, repair.Path,
        _ => throw new InvalidOperationException("Repair proceeded without reconfirmation."), Healthy, repair: true));
    var busyRepair = await store.ActivateAsync(repair.Target, repair.Path, _ => Task.FromResult<IAsyncDisposable?>(null),
        (_, _) => throw new InvalidOperationException("Busy repair started a probe."),
        confirmCommit: _ => Task.CompletedTask, repair: true);
    Check(busyRepair is { Status: ActivationStatus.Busy, Current: null }, "repair still requires a quiesce lease");
    await ExpectAsync<IOException>(() => store.ActivateAsync(repair.Target, repair.Path, Pause, Healthy,
        confirmCommit: _ => throw new IOException("Repair candidate could not be reconfirmed."), repair: true));
    Check(store.Inspect() is { Runnable: null } afterFailure && afterFailure.Committed == next.Target,
        "a transient recovery failure does not reset the floor or reactivate the withdrawn release");

    var versions = Path.Combine(state, "versions");
    var abandoned = Directory.CreateDirectory(Path.Combine(versions, ".staging-" + Guid.NewGuid().ToString("N"))).FullName;
    var unknownDirectory = Directory.CreateDirectory(Path.Combine(versions, "00040")).FullName;
    if (!OperatingSystem.IsWindows())
    {
        // Creating a symlink on native Windows may require developer mode.
        Directory.CreateSymbolicLink(Path.Combine(abandoned, "linked"), scratch);
        Directory.CreateSymbolicLink(Path.Combine(versions, "40"), scratch);
    }
    var repaired = await store.ActivateAsync(repair.Target, repair.Path, Pause, Healthy,
        confirmCommit: _ => Task.CompletedTask, repair: true);
    Check(repaired.Status == ActivationStatus.Committed && store.Recover()?.Release == repair.Target,
        "a higher repair build can be selected after an isolated probe");
    Check(!Directory.Exists(abandoned) && !Directory.Exists(Path.Combine(versions, "42")) &&
        !Directory.Exists(Path.Combine(versions, "41")) && !Directory.Exists(Path.Combine(versions, "40")) &&
        Directory.Exists(unknownDirectory) && File.ReadAllText(business) == "unchanged",
        "slot cleanup preserves business files, does not follow links and removes retired and staging slots");
    var subsequent = CreatePayload(scratch, 58);
    var newest = CreatePayload(scratch, 59);
    targets.UnionWith([subsequent.Target, newest.Target]);
    await store.ActivateAsync(subsequent.Target, subsequent.Path, Pause, Healthy);
    await store.ActivateAsync(newest.Target, newest.Path, Pause, Healthy);
    Check(store.Recover()?.Release == newest.Target && Directory.Exists(Path.Combine(versions, "58")) &&
        !Directory.Exists(Path.Combine(versions, "57")), "steady state keeps only the current and previous trusted build");
    File.AppendAllText(Path.Combine(versions, "59", "payload", "AgentLink.exe"), "corrupted installed files");
    Check(store.Inspect() is { Runnable: null } damaged && damaged.Committed == newest.Target,
        "damaged installed bytes preserve the same version floor");
    var coldRepair = CreatePayload(scratch, 64);
    targets.Add(coldRepair.Target);
    Check((await store.ActivateAsync(coldRepair.Target, coldRepair.Path, Pause, Healthy,
        confirmCommit: _ => Task.CompletedTask, repair: true)).Current?.Release == coldRepair.Target,
        "higher signed repair also replaces corrupt, unwithdrawn bytes");
    Console.WriteLine("PASS: repair keeps its version floor, requires quiescence and fresh trust, and bounds owned slots.");
}
finally { Directory.Delete(scratch, recursive: true); }

static (PayloadRelease Target, string Path) CreatePayload(string root, long build, string? extra = null,
    int attributes = 0, bool badHash = false)
{
    var path = Path.Combine(root, build + ".zip");
    using (var zip = ZipFile.Open(path, ZipArchiveMode.Create))
    {
        var hashes = new List<object>();
        void Add(string name, string content, int flags = 0)
        {
            var entry = zip.CreateEntry(name);
            if (flags != 0) entry.ExternalAttributes = flags;
            var bytes = Encoding.UTF8.GetBytes(content);
            using var output = entry.Open();
            output.Write(bytes);
            hashes.Add(new { path = name, sha256 = badHash ? new string('0', 64) : Convert.ToHexString(SHA256.HashData(bytes)) });
        }
        Add("AgentLink.exe", "tray-" + build);
        Add("host/AgentLink.Host.exe", "host-" + build);
        Add("runtime/gateway-node.exe", "node-" + build);
        Add("components/gateway/device-gateway.mjs", "gateway-" + build);
        if (extra is not null) Add(extra, "unexpected", attributes);
        using var output = zip.CreateEntry("release-manifest.json").Open();
        if (build == 41) output.Write(new byte[] { 0xef, 0xbb, 0xbf });
        JsonSerializer.Serialize(output, new { schemaVersion = 1, product = "Agent Link", buildNumber = build, files = hashes });
    }
    return (ReadTarget(build, path), path);
}

static PayloadRelease ReadTarget(long build, string path)
{
    using var stream = File.OpenRead(path);
    return new(build, stream.Length, Convert.ToHexString(SHA256.HashData(stream)).ToLowerInvariant());
}

static void Check(bool value, string message)
{
    if (!value) throw new InvalidOperationException(message);
}

static void Expect<T>(Action action) where T : Exception
{
    try { action(); }
    catch (T) { return; }
    throw new InvalidOperationException("Expected " + typeof(T).Name);
}

static async Task ExpectAsync<T>(Func<Task> action) where T : Exception
{
    try { await action(); }
    catch (T) { return; }
    throw new InvalidOperationException("Expected " + typeof(T).Name);
}

static Task<IAsyncDisposable?> Pause(CancellationToken _) => Task.FromResult<IAsyncDisposable?>(new Lease());
static async Task<bool> Healthy(InstalledPayload payload, CancellationToken cancellation)
{
    using var child = Start("health", payload.Directory, payload.Release.BuildNumber.ToString());
    await child.WaitForExitAsync(cancellation);
    return child.ExitCode == 0;
}

static Process Start(params string[] arguments)
{
    var start = new ProcessStartInfo(Environment.ProcessPath!) { UseShellExecute = false };
    if (Path.GetFileNameWithoutExtension(start.FileName).Equals("dotnet", StringComparison.OrdinalIgnoreCase))
        start.ArgumentList.Add(typeof(Program).Assembly.Location);
    foreach (var argument in arguments) start.ArgumentList.Add(argument);
    return Process.Start(start) ?? throw new InvalidOperationException("Could not start test fixture.");
}

sealed class Lease : IAsyncDisposable
{
    public ValueTask DisposeAsync() => ValueTask.CompletedTask;
}
